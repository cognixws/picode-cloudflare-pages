test("removal deletes the analytics site; a lost delete holds without repeating",async t=>{
 const f=fixture(t),op=await f.service.prepare({artifactId:"a1",version:1,analytics:true});await f.confirm(op);
 const p=f.service.pub(op.publication_id),tag=p.analytics_tag,orig=f.remote.deleteRumSite;
 let lost=true;
 f.remote.deleteRumSite=async t2=>{await orig(t2);if(lost){lost=false;throw new RemoteError("response lost");}};
 const remove=await f.service.prepare({action:"remove",publicationId:p.id});await f.confirm(remove);
 assert.equal(f.service.op(remove.id).status,"unknown");
 assert.equal(f.projects.size,0);
 f.service.reconcile(remove.id);await f.settle();
 assert.equal(f.service.op(remove.id).status,"removed");
 assert.equal(f.calls.filter(c=>c==="rum-delete").length,2);
 assert.equal(f.service.pub(p.id).analytics_tag,null);
 assert.equal([...f.rumSites.values()].some(s=>s.site_tag===tag),false);
});
test("a failing analytics cleanup keeps removal open until the site is gone",async t=>{
 const f=fixture(t),op=await f.service.prepare({artifactId:"a1",version:1,analytics:true});await f.confirm(op);
 const p=f.service.pub(op.publication_id);
 f.remote.deleteRumSite=async()=>{throw new RemoteError("Cloudflare refused the request (HTTP 500).");};
 const remove=await f.service.prepare({action:"remove",publicationId:p.id});await f.confirm(remove);
 assert.equal(f.service.op(remove.id).status,"unknown");
 f.service.reconcile(remove.id);await f.settle();
 assert.equal(f.service.op(remove.id).status,"unknown");
 assert.equal(f.service.pub(p.id).status,"published");
 assert.equal(f.rumSites.size,1);
 f.remote.deleteRumSite=async tag=>{f.rumSites.delete(p.project+".pages.dev");};
 f.service.reconcile(remove.id);await f.settle();
 assert.equal(f.service.op(remove.id).status,"removed");
 assert.equal(f.service.pub(p.id).analytics_tag,null);
});
test("upload progress is tracked per file and exposed in state",async t=>{
 const f=fixture(t),s=f.service;
 f.bundles.get(1).files=[{path:"a.html"},{path:"b.html"},{path:"c.html"}];
 const orig=f.remote.deploy;
 f.remote.deploy=async(name,bundle,marker,onProgress)=>{for(let i=0;i<3;i++)onProgress();return orig(name,bundle,marker,onProgress);};
 const op=await s.prepare({artifactId:"a1",version:1,analytics:true});await f.confirm(op);
 assert.equal(s.op(op.id).status,"published");
 const row=(await s.state()).publications[0].operations.find(o=>o.id===op.id);
 assert.deepEqual(row.progress,{uploaded:3,total:3});
});
